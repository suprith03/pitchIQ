CREATE TABLE teams (
  team_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(120 CHAR) NOT NULL UNIQUE,
  crest_url VARCHAR2(500 CHAR),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE players (
  player_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id NUMBER NOT NULL REFERENCES teams(team_id),
  name VARCHAR2(160 CHAR) NOT NULL,
  position VARCHAR2(20 CHAR),
  shirt_number NUMBER(2),
  CONSTRAINT uq_player_team_name UNIQUE (team_id, name),
  CONSTRAINT ck_player_shirt_number CHECK (shirt_number IS NULL OR shirt_number BETWEEN 1 AND 99)
);

CREATE TABLE matches (
  match_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_id VARCHAR2(80 CHAR) UNIQUE,
  matchday NUMBER(3) NOT NULL,
  match_date TIMESTAMP WITH TIME ZONE NOT NULL,
  home_team_id NUMBER NOT NULL REFERENCES teams(team_id),
  away_team_id NUMBER NOT NULL REFERENCES teams(team_id),
  home_goals NUMBER(2),
  away_goals NUMBER(2),
  status VARCHAR2(20 CHAR) NOT NULL,
  CONSTRAINT ck_match_teams_differ CHECK (home_team_id <> away_team_id),
  CONSTRAINT ck_match_scores CHECK (
    (home_goals IS NULL AND away_goals IS NULL)
    OR (home_goals BETWEEN 0 AND 30 AND away_goals BETWEEN 0 AND 30)
  ),
  CONSTRAINT ck_match_status CHECK (status IN ('FINISHED', 'SCHEDULED', 'TIMED', 'IN_PLAY', 'POSTPONED')),
  CONSTRAINT ck_finished_match_has_score CHECK (status <> 'FINISHED' OR home_goals IS NOT NULL)
);

CREATE UNIQUE INDEX uq_match_fixture
  ON matches (SYS_EXTRACT_UTC(match_date), home_team_id, away_team_id);

CREATE TABLE goal_events (
  goal_event_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id NUMBER NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE,
  player_id NUMBER REFERENCES players(player_id),
  team_id NUMBER NOT NULL REFERENCES teams(team_id),
  minute NUMBER(3) NOT NULL,
  stoppage_minute NUMBER(2) DEFAULT 0 NOT NULL,
  is_own_goal NUMBER(1) DEFAULT 0 NOT NULL,
  is_penalty NUMBER(1) DEFAULT 0 NOT NULL,
  CONSTRAINT ck_goal_minute CHECK (minute BETWEEN 0 AND 130),
  CONSTRAINT ck_goal_stoppage CHECK (stoppage_minute BETWEEN 0 AND 30),
  CONSTRAINT ck_goal_flags CHECK (is_own_goal IN (0, 1) AND is_penalty IN (0, 1))
);

CREATE TABLE player_match_stats (
  player_match_stat_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id NUMBER NOT NULL REFERENCES players(player_id),
  match_id NUMBER NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE,
  minutes_played NUMBER(3) DEFAULT 0 NOT NULL,
  goals NUMBER(2) DEFAULT 0 NOT NULL,
  assists NUMBER(2) DEFAULT 0 NOT NULL,
  penalties_scored NUMBER(2) DEFAULT 0 NOT NULL,
  shots NUMBER(3) DEFAULT 0 NOT NULL,
  CONSTRAINT uq_player_match_stat UNIQUE (player_id, match_id),
  CONSTRAINT ck_player_minutes CHECK (minutes_played BETWEEN 0 AND 130),
  CONSTRAINT ck_player_stats_nonnegative CHECK (goals >= 0 AND assists >= 0 AND penalties_scored >= 0 AND shots >= 0)
);

CREATE TABLE standings (
  team_id NUMBER PRIMARY KEY REFERENCES teams(team_id) ON DELETE CASCADE,
  position NUMBER(3) NOT NULL UNIQUE,
  played NUMBER(3) DEFAULT 0 NOT NULL,
  won NUMBER(3) DEFAULT 0 NOT NULL,
  drawn NUMBER(3) DEFAULT 0 NOT NULL,
  lost NUMBER(3) DEFAULT 0 NOT NULL,
  goals_for NUMBER(4) DEFAULT 0 NOT NULL,
  goals_against NUMBER(4) DEFAULT 0 NOT NULL,
  goal_difference NUMBER(5) DEFAULT 0 NOT NULL,
  points NUMBER(4) DEFAULT 0 NOT NULL,
  form VARCHAR2(5 CHAR),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_standings_counts CHECK (played = won + drawn + lost)
);

CREATE INDEX ix_matches_date ON matches(match_date);
CREATE INDEX ix_matches_home_date ON matches(home_team_id, match_date);
CREATE INDEX ix_matches_away_date ON matches(away_team_id, match_date);
CREATE INDEX ix_goal_events_match ON goal_events(match_id);
CREATE INDEX ix_goal_events_player ON goal_events(player_id);
CREATE INDEX ix_player_stats_match ON player_match_stats(match_id);
CREATE INDEX ix_players_team ON players(team_id);

CREATE OR REPLACE PROCEDURE validate_match_results AS
  invalid_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO invalid_count
  FROM matches
  WHERE (status = 'FINISHED' AND (home_goals IS NULL OR away_goals IS NULL))
     OR (home_goals IS NOT NULL AND (home_goals > 30 OR away_goals > 30));
  IF invalid_count > 0 THEN
    RAISE_APPLICATION_ERROR(-20001, 'Match result validation failed: finished matches require valid scores.');
  END IF;
END;
