CREATE OR REPLACE PROCEDURE recalculate_standings AS
BEGIN
  DELETE FROM standings;
  INSERT INTO standings (
    team_id, position, played, won, drawn, lost, goals_for, goals_against,
    goal_difference, points, form
  )
  WITH finished AS (
    SELECT match_id, match_date, home_team_id, away_team_id, home_goals, away_goals
    FROM matches
    WHERE status = 'FINISHED' AND home_goals IS NOT NULL AND away_goals IS NOT NULL
  ),
  totals AS (
    SELECT team_id,
      COUNT(match_id) AS played,
      SUM(won) AS won,
      SUM(drawn) AS drawn,
      SUM(lost) AS lost,
      SUM(goals_for) AS goals_for,
      SUM(goals_against) AS goals_against,
      SUM(points) AS points
    FROM (
      SELECT f.match_id, f.home_team_id AS team_id,
        CASE WHEN f.home_goals > f.away_goals THEN 1 ELSE 0 END AS won,
        CASE WHEN f.home_goals = f.away_goals THEN 1 ELSE 0 END AS drawn,
        CASE WHEN f.home_goals < f.away_goals THEN 1 ELSE 0 END AS lost,
        f.home_goals AS goals_for, f.away_goals AS goals_against,
        CASE WHEN f.home_goals > f.away_goals THEN 3 WHEN f.home_goals = f.away_goals THEN 1 ELSE 0 END AS points
      FROM finished f
      UNION ALL
      SELECT f.match_id, f.away_team_id,
        CASE WHEN f.away_goals > f.home_goals THEN 1 ELSE 0 END,
        CASE WHEN f.home_goals = f.away_goals THEN 1 ELSE 0 END,
        CASE WHEN f.away_goals < f.home_goals THEN 1 ELSE 0 END,
        f.away_goals, f.home_goals,
        CASE WHEN f.away_goals > f.home_goals THEN 3 WHEN f.away_goals = f.home_goals THEN 1 ELSE 0 END
      FROM finished f
    )
    GROUP BY team_id
  ),
  form_rows AS (
    SELECT team_id,
      LISTAGG(result, '') WITHIN GROUP (ORDER BY match_date DESC, match_id DESC) AS form
    FROM (
      SELECT team_id, match_id, match_date, result,
        ROW_NUMBER() OVER (PARTITION BY team_id ORDER BY match_date DESC, match_id DESC) AS rn
      FROM (
        SELECT f.match_id, f.match_date, f.home_team_id AS team_id,
          CASE WHEN f.home_goals > f.away_goals THEN 'W' WHEN f.home_goals = f.away_goals THEN 'D' ELSE 'L' END AS result
        FROM finished f
        UNION ALL
        SELECT f.match_id, f.match_date, f.away_team_id,
          CASE WHEN f.away_goals > f.home_goals THEN 'W' WHEN f.away_goals = f.home_goals THEN 'D' ELSE 'L' END
        FROM finished f
      )
    )
    WHERE rn <= 5
    GROUP BY team_id
  ),
  ranked AS (
    SELECT t.team_id,
      NVL(s.played, 0) AS played, NVL(s.won, 0) AS won,
      NVL(s.drawn, 0) AS drawn, NVL(s.lost, 0) AS lost,
      NVL(s.goals_for, 0) AS goals_for, NVL(s.goals_against, 0) AS goals_against,
      NVL(s.goals_for, 0) - NVL(s.goals_against, 0) AS goal_difference,
      NVL(s.points, 0) AS points, fr.form,
      ROW_NUMBER() OVER (
        ORDER BY NVL(s.points, 0) DESC,
          NVL(s.goals_for, 0) - NVL(s.goals_against, 0) DESC,
          NVL(s.goals_for, 0) DESC, t.name
      ) AS position
    FROM teams t
    LEFT JOIN totals s ON s.team_id = t.team_id
    LEFT JOIN form_rows fr ON fr.team_id = t.team_id
  )
  SELECT team_id, position, played, won, drawn, lost, goals_for, goals_against,
    goal_difference, points, form
  FROM ranked;
END;
